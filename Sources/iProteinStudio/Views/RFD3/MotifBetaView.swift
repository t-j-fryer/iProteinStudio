import SwiftUI
import AppKit

struct MotifBetaView: View {
    let project: Project
    @Environment(\.dismiss) private var dismiss
    @StateObject private var model = MotifBetaModel()
    @State private var selected = "M0040_13pk"
    @State private var length = 180
    @State private var roots = 1
    @State private var cycles = 2
    @State private var proposals = 4
    @State private var guidance = true
    @State private var guidanceSource = "rfd3-root"

    var body: some View {
        VStack(alignment: .leading, spacing: 16) {
            HStack {
                Text("Template-guided Boltz motif beta").font(.title2.bold())
                Spacer()
                Button("Done") { dismiss() }
            }
            Text("Original AME-41 motifs and ligands. CPU input and template checks and a small end-to-end KSI test with pause/resume have passed. Broader design performance remains unvalidated. The paper’s 38-case subset is unverified. Pilots are limited to 1–5 roots.")
                .foregroundStyle(.secondary)
            MemoryPolicyControl()
            ScrollView {
                VStack(alignment: .leading, spacing: 16) {
                    Picker("Benchmark motif", selection: $selected) {
                        ForEach(model.cases) { c in Text(c.label).tag(c.case_id) }
                    }
                    if let item = model.cases.first(where: { $0.case_id == selected }) {
                        GroupBox("Exact source atoms and ligand instances") {
                            Text(item.detail).font(.caption.monospaced()).textSelection(.enabled)
                                .frame(maxWidth: .infinity, alignment: .leading).padding(6)
                        }
                        if let url = URL(string: "https://www.rcsb.org/structure/\(item.pdb_id)") {
                            Link("Original protein structure: \(item.pdb_id)", destination: url)
                        }
                    }
                    Stepper("Scaffold length: \(length) residues", value: $length, in: 50...400, step: 10)
                    Stepper("Pilot roots: \(roots)", value: $roots, in: 1...5)
                    GroupBox("Paired comparison") {
                        VStack(alignment: .leading, spacing: 10) {
                            Text("LigandMPNN × LASErMPNN; fixed sampling, independent iteration, greedy and beam (width 4).")
                            Stepper("Cycles: \(cycles)", value: $cycles, in: 1...10)
                            Stepper("Proposals per cycle and arm: \(proposals)", value: $proposals, in: 1...32)
                            Toggle("Guide proposals with mapped motif residues", isOn: $guidance)
                            Picker("Motif residue geometry", selection: $guidanceSource) {
                                Text("Generated RFD3 residues").tag("rfd3-root")
                                Text("Original benchmark residues").tag("benchmark-residues")
                            }.disabled(!guidance)
                            Text("Boltz-2 cycling · \(roots * cycles * proposals) proposals per arm · untemplated checks drive selection.")
                                .font(.caption).foregroundStyle(.secondary)
                        }.padding(6)
                    }
                    Text(guidanceSource == "rfd3-root"
                        ? "Use the motif residue frames generated by RFD3. Original catalytic atoms remain the scoring reference."
                        : "Use the disconnected original motif residues, including their native backbone frames, at the sequence positions assigned by RFD3. This adds native geometry beyond the benchmark’s selected atoms.")
                    Text("Templates guide geometry; they do not lock catalytic atoms or ligand poses. A complete protein is not needed to store a motif, but folding needs a full query sequence and a residue-position map.")
                        .font(.caption).foregroundStyle(.secondary)
                    Text("Backbones are ranked by motif RMSD to the original input before fixed atoms are copied into the export. Every checked prediction retains its input-to-sequence mapping and input-motif RMSD.")
                        .font(.caption).foregroundStyle(.secondary)
                    Text("Beta results require a separate predictor-family check and laboratory validation. Protenix and IntelliFold sparse template features have passed CPU checks; model inference and automatic cycling remain unqualified.")
                        .font(.caption).foregroundStyle(.secondary)
                    if !model.message.isEmpty { Text(model.message).textSelection(.enabled) }
                    if !model.log.isEmpty {
                        Text(model.log.suffix(10).joined(separator: "\n")).font(.caption.monospaced()).textSelection(.enabled)
                    }
                }
            }
            HStack {
                Button("Prepare inputs") { start("prepare") }.disabled(model.busy)
                Button("Backbone pilot") { start("backbones") }.disabled(model.busy || !RFD3Controller.isAvailable)
                Button("Run beta comparison") { start("cycles") }
                    .buttonStyle(.borderedProminent).disabled(model.busy || !RFD3Controller.isAvailable)
                if model.busy { Button("Stop") { model.cancel() } }
                if let folder = model.output { Button("Open files") { NSWorkspace.shared.open(folder) } }
            }
        }.padding(24).frame(width: 780, height: 720)
            .onAppear { model.loadCatalog() }
    }

    private func start(_ stage: String) {
        model.start(project: project, settings: ["schema": 1, "case_id": selected,
            "length": length, "roots": roots, "cycles": cycles, "proposals": proposals,
            "engine": "boltz", "guidance": guidance, "guidance_source": guidanceSource, "stage": stage])
    }
}

private struct MotifBetaCase: Decodable, Identifiable {
    struct Residue: Decodable {
        let component: String
        let chain: String
        let residue: Int
        let source_selector: String?
        let conditioning_atoms: [String]?
    }
    let case_id: String
    let pdb_id: String
    let protein_motif: [Residue]
    let ligands: [Residue]
    var id: String { case_id }
    var label: String { case_id + " · " + ligands.map(\.component).joined(separator: ", ") }
    var detail: String {
        (protein_motif.map { "\($0.component) \($0.source_selector ?? "") · \(($0.conditioning_atoms ?? []).joined(separator: ", "))" }
         + ligands.map { "\($0.component) · \($0.chain)\($0.residue) · fixed ligand" }).joined(separator: "\n")
    }
}

@MainActor
private final class MotifBetaModel: ObservableObject {
    @Published var cases: [MotifBetaCase] = []
    @Published var message = ""
    @Published var log: [String] = []
    @Published var busy = false
    @Published var output: URL?
    private let job = ManagedJobSession()

    func loadCatalog() {
        do {
            guard let pipeline = AppPaths.bundledPipeline else { throw NHError.message("Bundled beta inputs are missing.") }
            struct Catalog: Decodable { let cases: [MotifBetaCase] }
            cases = try JSONDecoder().decode(Catalog.self, from: Data(contentsOf:
                pipeline.appendingPathComponent("scripts/motif_beta/data/inventory.json"))).cases
        } catch { message = error.localizedDescription }
    }

    func start(project: Project, settings: [String: Any]) {
        guard !busy else { return }
        do {
            try AppPaths.stagePipelineAssets()
            let directory = AppPaths.projectDir(project).appendingPathComponent("motif_beta/\(UUID().uuidString)")
            try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
            try JSONSerialization.data(withJSONObject: settings, options: [.prettyPrinted, .sortedKeys])
                .write(to: directory.appendingPathComponent("motif_beta_request.json"), options: .atomic)
            output = directory; busy = true; log = []
            job.submit(project: project.slug, workflow: "motif_beta", output: directory,
                preparing: { [weak self] in self?.message = $0 },
                update: { [weak self] value in
                    self?.busy = value.isActive
                    self?.message = value.error ?? value.message ?? value.displayStatus
                    self?.log = value.pipeline_log_tail ?? []
                }, failure: { [weak self] error in self?.busy = false; self?.message = error })
        } catch { message = error.localizedDescription; busy = false }
    }

    func cancel() { job.cancel() }
}
